const DREAMUP = "DeviantArt DreamUp";

/** The tool is named per picture, so the credit shown with it is true for that picture. */
function picture(src: string, alt: string, tool: string = DREAMUP): Artwork {
  return { src, alt, credit: `AI-generated image (${tool}), made by the Salvage Rights team.`, permission: `Generated by the Salvage Rights team with ${tool}` };
}

